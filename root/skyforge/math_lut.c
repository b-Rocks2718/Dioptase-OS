/* Pack 4-bit red, green, and blue channels into a 12-bit 0x0BGR color word. */
static unsigned short rgb12(int r, int g, int b){
  if (r < 0) r = 0;
  if (r > 15) r = 15;
  if (g < 0) g = 0;
  if (g > 15) g = 15;
  if (b < 0) b = 0;
  if (b > 15) b = 15;
  return (unsigned short)((b << 8) | (g << 4) | r);
}

/* Return 16.16 sine of 10-bit angle `a`. */
int isin(int a){
  return sin_lut[a & ANGLE_MASK];
}

/* Return 16.16 cosine of 10-bit angle `a`. */
int icos(int a){
  return sin_lut[(a + ANGLE_QUARTER) & ANGLE_MASK];
}

/* Multiply two signed 16.16 fixed-point numbers using 8.8 intermediate scale. */
int fixmul(int a, int b){
  int sa = a >> 8;
  int sb = b >> 8;
#ifdef SKYFORGE_HOST_TEST
  return sa * sb;
#else
  int neg = 0;
  if (sa < 0){
    sa = -sa;
    neg = !neg;
  }
  if (sb < 0){
    sb = -sb;
    neg = !neg;
  }
  int prod = (int)umul16((unsigned)(sa & 0xFFFF), (unsigned)(sb & 0xFFFF));
  return neg ? -prod : prod;
#endif
}

/* Return fast octant approximation of 2D distance |(dx, dy)|. */
int approx_dist2d(int dx, int dy){
  if (dx < 0) dx = -dx;
  if (dy < 0) dy = -dy;
  int hi = dx > dy ? dx : dy;
  int lo = dx > dy ? dy : dx;
  return hi + (lo >> 1) - (lo >> 3);
}

/* Expand a 12-bit 0x0BGR color into a duplicated 32-bit pixel-pair word. */
unsigned pack_pair(unsigned short c){
  unsigned u = (unsigned)c & 0x0FFF;
  return u | (u << 16);
}

/* Blend a 12-bit 0x0BGR color toward `fog` by `fog_level` (0..8). */
unsigned short shade_color12(unsigned short col, unsigned short fog, int fog_level){
  if (fog_level <= 0) return col;
  if (fog_level >= 8) return fog;
  int keep = 8 - fog_level;
  int r = (((col & 15) * keep) + ((fog & 15) * fog_level)) >> 3;
  int g = ((((col >> 4) & 15) * keep) + (((fog >> 4) & 15) * fog_level)) >> 3;
  int b = ((((col >> 8) & 15) * keep) + (((fog >> 8) & 15) * fog_level)) >> 3;
  return rgb12(r, g, b);
}

/* Compute one 12-bit terrain color for biome `b`, height `h` (0..63), and
 * slope/material band `light` (0 = shadow, 1 = flat, 2 = sunlit, 3 = accent). */
static unsigned short make_biome_color(int b, int h, int light){
  int r = 0;
  int g = 0;
  int bl = 0;
  int delta = (light == 0) ? -2 : (light == 2 ? 2 : 0);

  if (b == BIOME_EMERALD){
    /* Dioptase Emerald Basin: sapphire river, emerald slopes, snow peaks */
    if (light == 3){
      /* Glowing emerald dioptase crystal vein */
      return rgb12(2, 15, 11);
    }
    if (h <= WATER_LEVEL){
      r = 1;
      g = 5 + (h >> 1) + (light == 2 ? 2 : 0);
      bl = 10 + (h >> 1) + (light == 2 ? 2 : 0);
      return rgb12(r, g, bl);
    } else if (h <= 11){
      r = 9 + delta; g = 10 + delta; bl = 6 + delta;
    } else if (h <= 34){
      int t = (h - 12) >> 2;
      r = 2 + (t >> 1) + delta;
      g = 11 - (t >> 1) + delta;
      bl = 5 + (t >> 1) + delta;
    } else if (h <= 50){
      int t = (h - 35) >> 2;
      r = 6 + t + delta;
      g = 7 + t + delta;
      bl = 8 + t + delta;
    } else {
      r = 13 + delta; g = 14 + delta; bl = 15;
    }
  } else if (b == BIOME_OBSIDIAN){
    /* Obsidian Magma Caldera: molten lava rivers, basalt cliffs, ember rims */
    if (light == 3){
      return rgb12(15, 12, 2);
    }
    if (h <= WATER_LEVEL){
      r = 15;
      g = 5 + h + (light == 2 ? 3 : 0);
      bl = 1 + (light == 2 ? 2 : 0);
      return rgb12(r, g, bl);
    } else if (h <= 14){
      r = 11 + delta; g = 4 + delta; bl = 2;
    } else if (h <= 42){
      int t = (h - 15) >> 3;
      r = 5 + t + delta;
      g = 3 + t + delta;
      bl = 4 + t + delta;
    } else {
      int t = (h - 43) >> 2;
      r = 11 + t + delta;
      g = 5 + t + delta;
      bl = 3 + delta;
    }
  } else if (b == BIOME_CRYO){
    /* Cryo-Spire Sea: deep arctic water, cyan glaciers, diamond peaks */
    if (light == 3){
      return rgb12(6, 15, 15);
    }
    if (h <= WATER_LEVEL){
      r = 1;
      g = 4 + (h >> 1) + (light == 2 ? 2 : 0);
      bl = 9 + (h >> 1) + (light == 2 ? 2 : 0);
      return rgb12(r, g, bl);
    } else if (h <= 30){
      int t = (h - 9) >> 2;
      r = 4 + t + delta;
      g = 10 + (t >> 1) + delta;
      bl = 13 + (t >> 2) + delta;
    } else if (h <= 48){
      int t = (h - 31) >> 2;
      r = 7 + t + delta;
      g = 9 + t + delta;
      bl = 12 + (t >> 1) + delta;
    } else {
      r = 14 + delta; g = 15; bl = 15;
    }
  } else if (b == BIOME_CYBER){
    /* Cyber-Trench Nexus: synthwave neon grid & indigo/magenta ridges */
    if (light == 3){
      return rgb12(15, 3, 15);
    }
    if (h <= WATER_LEVEL){
      r = (light == 2) ? 14 : 3;
      g = (light == 2) ? 2 : 1;
      bl = (light == 2) ? 15 : 8;
      return rgb12(r, g, bl);
    } else if ((h & 7) == 0){
      /* Horizontal neon contour lines on canyon walls */
      return rgb12(2, 13, 15);
    } else {
      int t = h >> 3;
      r = 4 + t + delta;
      g = 1 + (t >> 1) + delta;
      bl = 8 + t + delta;
    }
  } else {
    /* Leviathan Dreadnought Sector: blood-gold twilight & metallic fortress */
    if (light == 3){
      return rgb12(15, 13, 3);
    }
    if (h <= WATER_LEVEL){
      r = 7 + (h >> 1) + (light == 2 ? 3 : 0);
      g = 1 + (light == 2 ? 2 : 0);
      bl = 4 + (h >> 1);
      return rgb12(r, g, bl);
    } else if (h <= 36){
      int t = (h - 9) >> 2;
      r = 6 + t + delta;
      g = 4 + (t >> 1) + delta;
      bl = 5 + (t >> 1) + delta;
    } else {
      int t = (h - 37) >> 2;
      r = 11 + t + delta;
      g = 9 + t + delta;
      bl = 4 + delta;
    }
  }
  return rgb12(r, g, bl);
}

/* Initialize the 1024-entry sine LUT, 5 biome palettes, and 5 sky gradients. */
void math_init(void){
  /* Populate quadrant 0 (0..256) by interpolating sin_quad65 */
  for (int i = 0; i <= 256; ++i){
    int idx = i >> 2;
    int frac = i & 3;
    int v0 = sin_quad65[idx];
    int v1 = (idx < 64) ? sin_quad65[idx + 1] : 65536;
    int val = v0 + (((v1 - v0) * frac) >> 2);
    if (i < 256) sin_lut[i] = val;
    if (i > 0 && i <= 256) sin_lut[512 - i] = val;
  }
  sin_lut[256] = 65536;
  for (int i = 0; i < 512; ++i){
    sin_lut[512 + i] = -sin_lut[i];
  }

  /* Populate biome palettes: index = (light << 6) | height */
  for (int b = 0; b < BIOME_COUNT; ++b){
    for (int light = 0; light < 4; ++light){
      for (int h = 0; h < 64; ++h){
        biome_palettes[(b << 8) | (light << 6) | h] = make_biome_color(b, h, light);
      }
    }
    /* Populate 32-band sky gradient from zenith (0) to horizon (31) */
    for (int s = 0; s < 32; ++s){
      int r = 0, g = 0, bl = 0;
      if (b == BIOME_EMERALD){
        r = 1 + (s >> 3);
        g = 3 + (s >> 1);
        bl = 6 + (s >> 2);
      } else if (b == BIOME_OBSIDIAN){
        r = 3 + ((s * 11) >> 5);
        g = 1 + (s >> 2);
        bl = 2 + (s >> 3);
      } else if (b == BIOME_CRYO){
        r = 1 + (s >> 2);
        g = 3 + ((s * 10) >> 5);
        bl = 7 + (s >> 2);
      } else if (b == BIOME_CYBER){
        r = 2 + ((s * 10) >> 5);
        g = 1 + (s >> 3);
        bl = 5 + (s >> 2);
      } else {
        r = 3 + ((s * 10) >> 5);
        g = 1 + (s >> 2);
        bl = 3 + (s >> 3);
      }
      sky_gradients[(b << 5) + s] = rgb12(r, g, bl);
    }
  }
}
