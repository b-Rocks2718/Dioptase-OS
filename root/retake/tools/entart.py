ORDER = ["coin", "heart", "frame", "reel", "ability", "mirror", "sign", "npc", "plate", "gate",
         "door", "walker", "hopper", "flyer", "thrower", "charger", "shot", "sandbag", "spring", "shop"]


def build():
    """Return [(name, [frames])] in ORDER; each frame is a packed image."""
    out = []
    for name in ORDER:
        frames = [pix.parse_ascii(rows, PAL) for rows in ART[name]]
        shape = frames[0].shape
        for f in frames:
            if f.shape != shape:
                raise SystemExit(f"entart.py: frames of '{name}' differ in size")
        out.append((name, frames))
    return out


if __name__ == "__main__":
    import sys
    import numpy as np
    items = build()
    canvas = pix.new_image(400, 80, pix.gray(7, warm=1))
    x = 4
    y = 4
    for name, frames in items:
        for f in frames:
            h, w = f.shape
            if x + w > 396:
                x = 4
                y += 28
            pix.blit(canvas, f, x, y)
            x += w + 4
    pix.write_png(sys.argv[1] if len(sys.argv) > 1 else "/tmp/retake-prev/ents.png", canvas, scale=4)


