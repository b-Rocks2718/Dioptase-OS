def build():
    """Return [(name, [frames])] in ORDER; each frame is a packed image."""
    out = []
    for name in ORDER:
        frames = [pix.parse_ascii(rows, PAL) for rows in ART[name]]
        shape = frames[0].shape
        for f in frames:
            if f.shape != shape:
                raise SystemExit(f"entart.py: frames of '{name}' differ in size")
        out.append((name, frames))
    return out


if __name__ == "__main__":
    import sys
