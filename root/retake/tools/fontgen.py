"""One-time generator for RETAKE's proportional intertitle fonts.

Rasterizes printable ASCII from a TrueType font with pango-view (hinted,
gray antialiasing) and writes the result as committed Python data
(tools/font_<name>.py), so the regular asset build has no pango dependency.

Fonts: DejaVu Serif (Bitstream Vera / DejaVu license, which permits
embedding and redistribution; credited in README.md).

Usage: python3 tools/fontgen.py
"""
import os
import struct
import subprocess
import tempfile
import zlib

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
MARGIN = 4

FONTS = {
    # name: (pango font description, baseline row from the cell top, cell height)
    "serif": ("DejaVu Serif Condensed 8", None, None),
    "title": ("DejaVu Serif Condensed Bold 14", None, None),
}


def read_png_gray(path):
    """Minimal PNG decoder for pango-view's 8-bit RGB/RGBA output; returns
    the red channel as a (h, w) int array."""
    data = open(path, "rb").read()
    pos = 8
    idat = b""
    w = h = ct = bd = 0
    while pos < len(data):
        ln = struct.unpack(">I", data[pos:pos + 4])[0]
        typ = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + ln]
        pos += 12 + ln
        if typ == b"IHDR":
            w, h, bd, ct = struct.unpack(">IIBB", body[:10])
        elif typ == b"IDAT":
            idat += body
    raw = zlib.decompress(idat)
    ch = {0: 1, 2: 3, 4: 2, 6: 4}[ct]
    bpp = ch * bd // 8
    stride = w * bpp
    out = np.zeros((h, stride), dtype=np.int32)
    prev = np.zeros(stride, dtype=np.int32)
    i = 0
    for y in range(h):
        f = raw[i]
        i += 1
        line = np.frombuffer(raw[i:i + stride], dtype=np.uint8).astype(np.int32)
        i += stride
        cur = np.zeros(stride, dtype=np.int32)
        for x in range(stride):
            a = cur[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 0:
                v = line[x]
            elif f == 1:
                v = line[x] + a
            elif f == 2:
                v = line[x] + b
            elif f == 3:
                v = line[x] + ((a + b) >> 1)
            else:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                v = line[x] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c))
            cur[x] = v & 255
        out[y] = cur
        prev = cur
    return out.reshape(h, w, ch)[:, :, 0]


def render(desc, text, tmp):
    path = os.path.join(tmp, "g.png")
    subprocess.run(
        ["pango-view", "--no-display", f"--font={desc}", "--dpi=96", "--hinting=full",
         "--antialias=gray", f"--margin={MARGIN}", "--foreground=white", "--background=black",
         f"--text={text}", f"--output={path}"],
        check=True, capture_output=True)
    return read_png_gray(path)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        for name, (desc, _, _) in FONTS.items():
            # The width of "||" vs "|c|" gives each glyph's advance without
            # trusting pango-view's margins; the bitmap comes from a "|c|"
            # render with the bars masked off.
            bars = render(desc, "||", tmp)
            base_w = bars.shape[1]
            height = bars.shape[0]
            glyphs = {}
            for code in range(32, 127):
                ch = chr(code)
                img = render(desc, "|" + ch + "|", tmp)
                adv = img.shape[1] - base_w
                if img.shape[0] != height:
                    raise SystemExit(f"fontgen: {name} glyph {ch!r} rendered {img.shape[0]} rows, expected {height}")
                # locate the two bars: the first and last inked columns
                cols = np.where(img.max(axis=0) > 100)[0]
                left_bar_end = cols[0]
                while left_bar_end + 1 < img.shape[1] and img[:, left_bar_end + 1].max() > 100 and \
                        np.count_nonzero(img[:, left_bar_end + 1] > 100) > height // 2:
                    left_bar_end += 1
                bar_w = left_bar_end - cols[0] + 1
                start = cols[0] + bar_w
                cell = img[:, start:start + adv + 2] if adv > 0 else np.zeros((height, 1), dtype=np.int32)
                levels = np.clip((cell + 32) // 64, 0, 3)
                rows = ["".join(" .+#"[v] for v in row) for row in levels]
                glyphs[ch] = (adv, rows)
            # trim common empty rows top and bottom
            all_rows = [r for _, rows in glyphs.values() for r in rows]
            top = 0
            while all(rows[top].strip() == "" for _, rows in glyphs.values()):
                top += 1
            bottom = height
            while all(rows[bottom - 1].strip() == "" for _, rows in glyphs.values()):
                bottom -= 1
            out = [f'"""Generated by tools/fontgen.py from {desc} -- do not edit by hand."""',
                   f"HEIGHT = {bottom - top}", "GLYPHS = {"]
            for ch, (adv, rows) in glyphs.items():
                out.append(f"    {ch!r}: ({adv}, {[r[: max(adv, 1) + 1] for r in rows[top:bottom]]!r}),")
            out.append("}")
            with open(os.path.join(HERE, f"font_{name}.py"), "w") as f:
                f.write("\n".join(out) + "\n")
            print(f"font_{name}: height {bottom - top}, {len(glyphs)} glyphs")


if __name__ == "__main__":
    main()
